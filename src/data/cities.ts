/** Türkçe büyük/küçük harf kurallarına uygun normalizasyon (İ→i, I→ı). */
function normalizeTurkish(value: string): string {
  return value
    .trim()
    .replace(/İ/g, 'i')
    .replace(/I/g, 'ı')
    .replace(/Ğ/g, 'ğ')
    .replace(/Ü/g, 'ü')
    .replace(/Ş/g, 'ş')
    .replace(/Ö/g, 'ö')
    .replace(/Ç/g, 'ç')
    .toLowerCase();
}

/** İl adına göre (büyük/küçük harf duyarsız, Türkçe uyumlu) il kaydını bulur. */
export function findCity(name: string): City | undefined {
  const target = normalizeTurkish(name);
  if (target.length === 0) {
    return undefined;
  }
  return TURKISH_CITIES.find((city) => normalizeTurkish(city.name) === target);
}
